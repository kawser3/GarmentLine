// PLAN §2: define the eleven collections, reload the gateway
// configuration, then read the generated operation names back.
//
// Idempotent: /data/v4/schemas/define is POST for a new schema and PUT for an
// existing one, so a re-run updates rather than duplicates.
//
//   node scripts/01-define-schemas.mjs
import fs from 'node:fs';
import path from 'node:path';
import { session, ROOT_DIR } from './blocks.mjs';
import { schemas } from './schemas.mjs';

const s = await session();

async function listSchemas() {
  const r = await s.api('/data/v4/schemas?PageNo=1&PageSize=200', { method: 'GET' });
  return r.data.items || [];
}

const existing = new Map((await listSchemas()).map(x => [x.schemaName, x]));
console.log(`existing schemas: ${existing.size}`);

for (const def of schemas) {
  const already = existing.get(def.schemaName);
  // collectionName is mandatory. Blocks' own convention (seen in the finance
  // project) is sb_<naive plural>, e.g. sb_Wings, sb_BillingEntrys.
  const body = {
    // PUT rejects a body without itemId ("ItemId_Is_Required"), even though the
    // published request model does not mention the field.
    ...(already ? { itemId: already.id } : {}),
    collectionName: already?.collectionName ?? `sb_${def.schemaName}s`,
    schemaName: def.schemaName,
    schemaType: 1,
    fields: def.fields.map(f => ({
      name: f.name,
      type: f.type,
      isArray: !!f.isArray,
      isPIIData: !!f.isPIIData,
      isUniqueData: !!f.isUniqueData,
      description: f.description || '',
      requiredOn: f.requiredOn || 'None',
    })),
  };
  const method = already ? 'PUT' : 'POST';
  try {
    const r = await s.api('/data/v4/schemas/define', { method, body });
    console.log(`  ${method.padEnd(4)} ${def.schemaName.padEnd(20)} ok  (${def.fields.length} fields)`);
    if (r?.isSuccess === false) console.log('       !!', JSON.stringify(r.errors));
  } catch (e) {
    console.log(`  ${method.padEnd(4)} ${def.schemaName.padEnd(20)} FAILED ${e.message.slice(0, 300)}`);
  }
}

// Nothing is visible to the gateway until the reload returns data: true.
console.log('\nreloading schema configuration...');
const reload = await s.api('/data/v4/schema-configurations/reload', { body: {} });
console.log('  reload ->', JSON.stringify(reload).slice(0, 300));

// The plan says to reload until unadapted-change-logs is empty. On this tenant
// that log never drains (every define leaves a doesServerAdaptChanges:false row
// behind) yet the gateway adapts anyway - so the real readiness check is
// introspecting the gateway for the operations we expect.
async function gatewayOps() {
  const r = await s.raw('/data/v4/gateway', {
    body: { query: '{ __schema { queryType { fields { name } } mutationType { fields { name } } } }' },
  });
  return {
    queries: (r.data?.data?.__schema?.queryType?.fields ?? []).map(f => f.name),
    mutations: (r.data?.data?.__schema?.mutationType?.fields ?? []).map(f => f.name),
  };
}

let ops = { queries: [], mutations: [] };
for (let i = 0; i < 10; i++) {
  ops = await gatewayOps();
  const missing = schemas.filter(d => !ops.queries.includes(`get${d.schemaName}s`) &&
    !ops.queries.some(q => q.startsWith(`get${d.schemaName}`)));
  console.log(`  gateway operations: ${ops.queries.length} queries, ${ops.mutations.length} mutations` +
    (missing.length ? ` (waiting on ${missing.map(m => m.schemaName).join(', ')})` : ''));
  if (!missing.length) break;
  await s.api('/data/v4/schema-configurations/reload', { body: {} });
  await new Promise(r => setTimeout(r, 3000));
}

// Capture the generated names - pluralisation is generated, never guessable.
const final = await listSchemas();
const map = {};
for (const it of final) {
  // querySchema is the bare plural ("Incidents"); the gateway field is that
  // prefixed with get ("getIncidents"). Record what the gateway actually has.
  map[it.schemaName] = {
    collectionName: it.collectionName,
    querySchema: it.querySchema,
    query: ops.queries.find(q => q === `get${it.querySchema}`) ?? null,
    mutations: ops.mutations.filter(m => new RegExp(`^(insert|update|delete)(Many)?${it.schemaName}$`).test(m)),
    fields: it.fields.map(f => `${f.name}:${f.type}${f.isArray ? '[]' : ''}`),
  };
}
const out = path.join(ROOT_DIR, 'generated', 'schema-map.json');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, JSON.stringify(map, null, 2));

// The portal imports these rather than hand-deriving them - Blocks pluralises
// naively (SlaPolicy -> getSlaPolicys) and guessing is how you lose ten minutes.
const ts = `// GENERATED by scripts/01-define-schemas.mjs - do not edit.
// Blocks generates operation names; never hand-derive them.
// Regenerate with: node scripts/01-define-schemas.mjs

export const OPS = ${JSON.stringify(
  Object.fromEntries(Object.entries(map).map(([k, v]) => [k, {
    collection: v.collectionName,
    query: v.query,
    insert: v.mutations.find(m => m === `insert${k}`) ?? null,
    insertMany: v.mutations.find(m => m === `insertMany${k}`) ?? null,
    update: v.mutations.find(m => m === `update${k}`) ?? null,
    updateMany: v.mutations.find(m => m === `updateMany${k}`) ?? null,
    delete: v.mutations.find(m => m === `delete${k}`) ?? null,
    deleteMany: v.mutations.find(m => m === `deleteMany${k}`) ?? null,
  }])), null, 2)} as const;

export type SchemaName = keyof typeof OPS;

/** Fields Blocks adds to every entity - never declare these yourself. */
export const BASE_FIELDS = [
  'ItemId', 'CreatedDate', 'CreatedBy', 'LastUpdatedDate',
  'LastUpdatedBy', 'Language', 'OrganizationId', 'Tags',
] as const;

export const FIELDS = ${JSON.stringify(
  Object.fromEntries(Object.entries(map).map(([k, v]) => [k, v.fields])), null, 2)} as const;
`;
fs.writeFileSync(path.join(ROOT_DIR, 'generated', 'blocks-operations.ts'), ts);

console.log(`\ndefined ${final.length} schemas -> generated/schema-map.json`);
for (const [name, v] of Object.entries(map)) {
  console.log(`  ${name.padEnd(20)} query=${String(v.query).padEnd(22)} ${v.mutations?.join(', ')}`);
}
